#include <stdio.h>

int main(int argc, char const *argv[])
{

    // 定义变量
    int numaa;


    // 数组的概念
    // 数组是多个相同类型元素组成的一个集合
    
    // 数组类型： int数组，char数组, float数组, int * 数组, char * 数组,  甚至是 函数指针数组;

    // 定义数组 =>  数组元素的类型 数组名[数组长度]  => 定义一个指定类型指定长度的数组
    // int arr[10];  // 整型数组
    // char arr[10]; // 字符型数组
    // float arr[10];  // 浮点数组
    // int * arr[10]; // 整型指针数组
    // char * arr[10]; // 字符型指针数组
    // 数组的定义： 数组的前面有类型就是定义数组，  数组的前面没有类型则是访问数组

    // 正常初始化
    int arr1[5] = {5, 4, 3, 2, 1}; // 以列表的方式初始化
    // int arr2[5] = {6, 5, 4, 3, 2, 1}; // 数组元素个数确定时, 初始化列表{}中的元素个数不可以超过定义的元素个数，否则 会报警告
    int arr3[5] = {6, 5, 4, 3}; // 允许元素个数比定义的元素个数 少

    int arr4[] = {6, 5, 4, 3}; // 元素初始化列表确定时，[]内可以省略    （右侧的元素个数确定时， []内可以省略）
    // int arr5[];                // 既没有初始化列表, 又没有指定数组的元素个数， 程序会报错;   也就是 左边的元素个数 和 右边的初始化列表 必须指定一个

    char b[5] = {'a', 'b', 'c', 'd', 'e'};
    char *c[] = {"这么近", "这么美", "周末到河北"};

    // 修改数组：
    // 不允许这样赋值， 这样只是拿到下标为5的元素
    // 只有在定义时才可以列表组初始化 数组不能在声明后再次使用 [] 语法进行整体赋值
    // arr1[5] = {5, 4, 3, 2, 1};
    // 只能单个赋值 arr[0]=1, arr[1]=2 ...... ;



    // 不能用变量来作为数组定义里面[]里面的内容(C99标准之前)
    // C99标准，允许将非常量表达式作为数组的个数来定义数组，但是不能在定义的时候做初始化
    int num = 5;
    int a5[num]; // 可变数组， 不能在定义时初始化


    // 访问数组：
    printf("%d\n", arr4[1]); // 元素下标访问元素
    printf("%d\n", arr3[4]); // 初始化的长度不够，后面的元素为0 
    printf("%s\n", c[2]); // 
    printf("%c\n", b[2]); // 
    // printf("%d\n", arr3[4]); // 越界

    // 修改数组
    arr1[0] = 50;
    b[0] = 'A';
    c[1] = "这么近！！！";
    printf("%c\n", b[0]); // 
    printf("%s\n", c[1]); // 
    printf("%d\n", arr1[1]); 

    char string[] = "hello world"; // 定义数组, 在栈上分配内存并复制字符串内容
    // string[] = "hello"; // 报错 数组不能在声明后再次使用 [] 语法进行整体赋值
    string = "hello";  // 这里string 指向元素首地址, 是一个常量(地址), 不能改变常量地址的指向  就像不能再计算机中让 固定指向字符h的地址 指向 hello
    printf("%s\n", string);

    // strcpy(string, "hello");  要修改 string[] 存储的字符串, 使用 strcpy 函数

}



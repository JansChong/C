#include <stdio.h>

// int * 就是 &m;返回的地址
int *func(void)
{
    // 之前的局部变量, 随着函数结束，函数分配到的栈内存被系统收回，所以里面的局部变量的空间也被收回，返回局部变量的地址是访问不到的

    // 静态变量：static修饰的变量就叫做静态变量，这个变量从定义位置开始就被分配到内存的数据段里面， 直到程序退出才会释放， 静态局部变量只会初始化一次

    // 静态局部变量 存储在数据段里面，不存放在函数的栈内存中，不会随函数结束被释放
    static int m = 0;
    return &m; // 返回这个静态局部变量在数据段中的地址， 函数结束时函数的栈内存被释放，段地址没有被释放

    //  static int m = 0; // 两次函数调用， 只有第一次函数调用会执行并初始化， 后续的函数调用不再执行这一行
    //  m += 10;
    //  printf("m = %d\n", m); // 两次函数调用， 输出10， 20
    //  return 0;
}

int main(int argc, char const *argv[])
{

    // 指针变量访问 func() 返回的地址
    int *p = func(); // 定义一个指针变量

    // printf("m的地址 :%p\n", p); // p是指针变量p本身, 其值等于函数返回的 m的地址
    // printf("p的地址 :%p\n", &p); // &p是指针变量p 自己的地址, 即指针变量p自己在内存中的位置
    // printf("m的值 :%d\n", *p);  // *p 表示解引用, 这里是 p指向的地址(m的地址)中的值 也就是m的值: 0

    // *p = 10;  // *p 表示解引用， 这里对这个p指向的地址(m的地址)存的值 进行 赋值,  即 0 => 10;
    // printf("m的地址 :%p\n", p); // p是指针变量p本身, 这里指的是m的地址
    // printf("p的地址 :%p\n", &p); // &p是指针变量p的地址, 就是指针变量p自己在内存中的位置
    // printf("m的值 :%d\n", *p);  // *p 表示解引用, 这里是 p指向的地址(m的地址)中的值 10,  即m=10

    // 执行两次
    // func(); // m = 10
    // func(); // m = 20，  也就是说   static int m = 0; 只会执行一次初始化


    // 指针变量 不能 用scanf 的 &p 赋值？
    scanf("%d", &p); // 替换p的值
    printf("p的值（原m的地址） :%p\n", p); // p是指针变量p本身, 这里指的是m的地址
    // printf("p的地址 :%p\n", &p); // &p是指针变量p的地址, 就是指针变量p自己在内存中的位置
    printf("m的值 :%d\n", *p);  // *p 表示解引用, 这里是 p指向的地址(m的地址)中的值 10,  即m=10
}



// C++ 内联函数（inline function）是一种通过关键字 inline 声明的优化机制，旨在减少函数调用的开销。编译器会将函数体直接插入到每个调用点，从而避免常规的函数调用过程（如压栈、跳转、返回等），特别适用于‌小型且频繁调用‌的函数。
// 核心特性与机制
// ‌以空间换时间‌：内联展开消除了函数调用的栈帧管理开销，提升了执行速度，但会导致代码体积膨胀（每个调用点都复制一份函数代码）。
// ‌编译器建议而非命令‌：inline 关键字仅是给编译器的建议。编译器会根据函数体大小、复杂度（如是否包含循环、递归）以及优化策略，自主决定是否真正进行内联。若函数过大或逻辑复杂，编译器通常会忽略该建议。

// 内敛函数语法： 函数前放入 inline 关键字
inline int inline_func(int n)
{
    return n + n;
}

int func(int n)
{ // 没有内敛函数
    return n + n;
}

int main(int argc, char const *argv[])
{
    for (int i = 0; i < 10000000; i++)
    {
        // 保护现场
        int a = inline_func(i); // 调用内敛函数， 编译器可能直接替换为 int a = i + i;
        // 恢复现场

        // 保护现场
        // int b = func(i); // 调用函数
        // 恢复现场

        // 在调用函数时，在函数调用的位置会有保护现场和恢复现场的操作（每个操作大概是一条语句执行的时间），  如果函数的语法很简单（比如只有一条简单语句）， 在频繁调用函数时， 由于频繁的保护现场和恢复现场， 导致执行函数本身的执行时间只有 1/3， 而保护现场和恢复现场的时间占据了执行时间的 2/3）

        // 如果用内敛函数，inline 会给编译器建议。编译器会根据函数体大小、复杂度（如是否包含循环、递归）以及优化策略，自主决定是否真正进行内联； 如果编译器决定内联，则会把函数的内容替换到原本函数调用的位置执行， 不再调用原函数 从而避免保护现场和恢复现场的触发；
        
        // ‌最佳场景‌：
        //     简单的访问器（getter）和修改器（setter）函数。
        //     执行简单数学运算或逻辑判断的短小函数。
        //     在性能敏感循环中被高频调用的微小函数。
        // ‌无效或受限情况‌：
        //     ‌递归函数‌：通常无法内联，因为展开次数不确定。
        //     ‌复杂函数‌：包含循环、switch 或大量代码的函数，编译器往往拒绝内联以防止代码爆炸。
        //     ‌取地址操作‌：如果对内联函数取指针，编译器必须生成实际的函数代码，此时内联效果失效。
    }
}
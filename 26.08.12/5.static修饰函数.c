#include <stdio.h>

// 静态函数主要为了缩小函数的可见范围,减少与其它文件中重名函数冲突的概率 
// 静态函数一般定义在头文件中，然后被各个源文件包含


// 同时编译 0和5 两个文件时, 这里有歧义, 因为函数默认可以跨文件调用, 所以 0和5 重复定义了两个func2
void func2(void);
// 所以在 0文件 中定义的 func2 用 static修饰, 让0文件定义的函数仅在 0文件内使用, 防止函数重复定义的发生

int main(int argc, char const *argv[])
{

    // 静态函数无法被跨函数调用, 目的是防止函数重名, 把函数限制在它的作用域
    func2();
}


void func2(void){
    printf("本函数和 0.文件名.c 中定义的某个函数名一致, 也就是定义了两个相同的函数\n");
}
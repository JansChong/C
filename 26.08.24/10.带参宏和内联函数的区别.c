#include <stdio.h>

#define Text(a) printf("%d\n", (a) * 10);

int main(int argc, char const *argv[])
{

    // 带参宏和内敛函数
    // 很多时候内敛函数和带参宏可以相互替换使用
    // 区别：
    // 1、替换发生的位置不一样，带参宏是在预处理过程中，内敛函数是在编译过程中
    // 2、带参宏在做展开的时候不会检查语法，内敛函数是会检查语法的
    // 3、内敛函数在传参的时候，实参是运行结果进行传参，带参宏直接将表达式传参过去

    Text(1 + 2);
}
#include <stdio.h>

// 带参宏
// （1）语法格式
// #define 宏名(形参列表) 字串
// （2）说明
// 带参宏不需要指定返回值和形参类型
// 带参宏定义中，宏名和形参列表之间不能有空格，参数列表之间是可以加空格的
// 在宏定义中，字串内的形参通常要用括号括起来，避免直接替换过程中由于没有考虑到运算符优先级问题，导致逻辑错误

#define MAX(val1, val2) (val1 > val2 ? val1 : val2)
// 过程: 1.参数赋值，  2.整理字串(非计算)   3.字串替换

#define ADD(a, b) (a + b)

int main(int argc, char const *argv[])
{
    printf("10和12较大的值为：%d\n", MAX(10, 12));  // 10和12较大的值为：12

    printf("两数之和为：%d\n", ADD(1, 20) * 10); // 形参通常要用括号括起来，避免直接替换过程中由于没有考虑到运算符优先级问题，导致逻辑错误


    // 纯文本替换，不加括号容易因为运算符优先级问题导致逻辑错误
    // 1 + 20 * 10   => 没加括号 201
    // (1 + 20) * 10  => 加了括号 210
    
}
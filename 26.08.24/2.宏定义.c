// 预处理命令： gcc main.c xxx.c xxx.c -E  (多个文件不能编译出.i文件)
// 预处理命令： gcc main.c -E -o main.i  (单个文件可以编译出.i文件)

#include <stdio.h>

// 宏定义： 用一个标识符来表示一串字串，后面的代码中出现了该标识符，那么就全部替换成指定的这串字符

// #define 宏名 字串
// 宏名：是标识符的一种，命名规则和变量一样，一般宏名用大写字母
// 字串：可以是常量，表达式，if语句，函数，字符串。。。。。。
#define PI 2 + 1.14   // 宏: 纯文本替换，不会自行计算
#define PERIMETER  PI * 2 * 2  // 宏定义语句允许嵌套
#define uint unsigned int  // 宏定义可以表示数据类型，但是一般不这么做
// #define "WRAP" "这个宏名称被双引号包围，预处理过程不会对这个位置进行宏替换"

// （1）宏定义用宏名来表示一个字串，在宏展开的时候，用这个字串来取代宏，这个是一种简单粗暴的替换（替换在预处理过程替换，不会做任何检查，也不会做任何运算）
// （2）宏定义不是说明或语句，不能在末尾加分号, 否则分号也会作为整体的一部分 进行替换
// （3）宏写在函数体外，作用域从定义位置开始到程序结束，终止宏定义的作用域，写在函数体内，在定义位置到函数结束，作用域就结束
// （4）在代码中宏被双引号包围，预处理过程就不会对这个位置进行宏替换
// （5）宏定义语句允许嵌套
// （6）习惯上宏名一般全部大写，便于与变量区分
// （7）宏定义可以表示数据类型，但是一般不这么做

// 3.3、编译过程
// 1、预处理    2、编译        3、汇编        4、链接
// gcc编译代码的时候，宏替换在预处理过程完成

// 在ubuntu22, 宏定义可以跨文件使用？
void func1() {
    // 宏写在函数体内，在定义位置到函数结束，作用域就结束
    #define TEST "HELLO"
};

void func2()
{
    // 但是在这里可以跨函数使用上面定义的宏 TEST
    printf("跨函数使用宏：%s\n", TEST); // HELLO
};


int main(int argc, char const *argv[])
{
    // unsigned int a = 25;
    uint a = 25;

    printf("圆周率：%f\n", PI); //  纯文本替换，计算过程是程序处理的
    printf("半径为2的圆的周长：%f\n", PERIMETER); //  纯文本替换，计算过程是程序处理的
    // printf("\"宏被双引号包裹\": %s\n", WRAP); // 无效，不会进行宏替换
    func2();
}

    // 纯文本替换，不加括号容易因为运算符优先级问题导致逻辑错误
    // 1 + 20 * 10   => 没加括号 201
    // (1 + 20) * 10  => 加了括号 210
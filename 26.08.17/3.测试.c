#include <stdio.h>

// 全局变量 会被初始化为 0 
// 全局变量在数据段
int *sum;

void test(int a, int b){
   int res = a+b;
   sum = &res;
}


int main(int argc, char const *argv[])
{


    test(10, 20);
    printf("sum: %d\n", *sum);


    *sum = 300;
    printf("%d\n", *sum); // 被销毁了， 为什么还可以赋值和输出？

}



// 程序中定义了一个全局指针变量sum，它指向的是在test函数中定义的局部变量res。在test函数中，res是一个自动变量（auto变量，属于动态存储方式），当函数被调用时，res在栈上被分配内存空间用于存储a + b的结果。

// sum = &res;这行代码将sum指向了res的地址。但是当test函数执行完毕后，根据自动变量的特性，res所在的栈空间会被释放，res变量也就不存在了。

// 然而，在main函数中，printf("sum: %d\n", *sum);这行代码还能输出一个值，并且*sum = 300;也能执行看似成功的赋值操作，这是因为虽然res的内存已经被释放，但sum仍然保存着指向那块曾经属于res的内存地址。此时这块内存虽然不再属于res，但尚未被其他数据覆盖（属于未定义行为范畴），所以还能读取到一个值（这个值可能是之前残留的数据），并且能进行赋值操作。但这种行为是非常危险的，因为后续这块内存可能会被其他程序使用，一旦被覆盖，再进行读取和赋值操作就会导致程序出现不可预料的错误，比如崩溃或得到错误的结果。

// ‌最终答案‌：这是一种未定义行为，虽然代码能暂时输出和赋值，但res被销毁后其内存已释放，sum指向的是无效内存，后续操作可能导致程序错误。
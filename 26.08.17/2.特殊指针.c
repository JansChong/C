#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(int argc, char const *argv[])
{

    // 特殊指针:
    //  void指针，野指针，空指针，零指针，const指针，char指针

    // ********************************************************************************************
    // 5.1、void指针（泛型指针，通用指针，万能指针）
    // （1）当不确定后面具体需要什么类型的指针的时候
    // （2）典型应用：① malloc申请匿名空间    ② 参数赋值，函数传参
    // （3）void型指针的最大优点，可以赋值给任意类型的指针
    // （4）void指针，必须要确定其类型才能使用（赋值或取值）

    // void类型的指针可以赋值给任意类型的指针,  这里malloc函数返回一个void类型的指针
    int *p1 = malloc(4);  // 申请四个字节的空间,  因为p1是int, 所以*p1访问4字节地址
    char *p2 = malloc(4); // 申请四个字节的空间,  因为p2是char, 所以 *p2访问第一个字节的值, 剩下的偏移访问

    *p1 = 100;
    *p2 = 20;

    *(p2 + 1) = 'A';
    *(p2 + 2) = 'k';
    *(p2 + 3) = -2;

    printf("%d\n", *p1);       // 100
    printf("%d\n", *p2);       // 20
    printf("%c\n", *(p2 + 1)); // A
    printf("%c\n", *(p2 + 2)); // k
    printf("%d\n", *(p2 + 3)); // -2

    // void * 要传递给确定类型的指针才可以被访问
    void *p3 = malloc(20); // 这个指针是void类型, 不能直接赋值或取值 因为void不确定空间有多大, 无法偏移 和 确定取址范围
    // printf("%d\n", p3); // 错误

    int *p41 = p3;    // 把 p3取到的地址, 赋值给 p4,  相当于  int * p4 = malloc(20),
    float *p42 = p3;  // 访问到 malloc申请的20个空间
    char *p43 = p3;   // 访问到 malloc申请的20个空间
    double *p44 = p3; // 访问到 malloc申请的20个空间

    // ********************************************************************************************
    // 5.2 野指针
    // 概念： 指向一块未知区域的指针，被称为野指针。野指针是很危险的。 一般我们认为没有赋初值的指针变量就是野指针

    int *n; // 指针未初始化， 随机分配地址
    // *n = 100; // 段错误。 非法使用一块未初始化的空间： 往随机地址中赋值
    // printf("%d\n", *n); // 无意义的值

    // 危害：
    // 1、引用野指针，相当于非法访问非法的内存，常常会发生段错误（Segmentation fault）
    // 2、引用野指针，可能会破坏系统的关键数据，导致系统崩溃等严重后果

    // 产生原因：
    // 1、指针定义之后，未初始化
    // 2、指针指向的内存，被系统回收
    // free(n); 释放申请的空间, 释放空间有可能会导致野指针
    // 3、指针越界会导致野指针
    // 4、malloc申请空间失败
    // tips:
    // 如果申请空间成功， malloc函数返回一个void类型的指针
    // 如果申请空间失败， 则malloc返回一个NULL

    // int *p = malloc(1);
    int *p = malloc(1024 * 1024); // 申请堆空间
    if (p == NULL)
        printf("fail\n");
    else
        printf("success\n");
    free(p);
    *p = 10; // 段错误
    printf("%d\n", *p);

    // malloc申请小空间，free之后，空间不会解除映射，空间仍然可以被正常访问到，但是新的malloc申请的新的空间会将其覆盖
    // malloc里请大空间，free之后空间会解除映射，不能够再被访问到

    // 如何防止野指针:
    // 1、指针定义时，及时初始化
    // 2、绝不引用已被系统回收的内存
    // 3、确认所申请的内存边界，谨防越界

    // ******************************************************************************************************
    // 5.3 空指针 与 0指针
    // 很多情况下，我们不可避免的会遇到野指针，比如定义指针的时候无法立即为其分配一块恰当的内存，又或者指针所指向的内存被系统回收（释放）等等，一般的做法就是将这些危险的野指针指向一块确定的内存，比如零地址内存

    // 概念: 值为NULL的指针就是空指针
    printf("%p\n", &NULL);             // (nil)
    printf("%lld\n", (long long)NULL); // 0  (ubuntu22)
    int *q = NULL;
    // int *q = 0; // 在 Ubuntu， 空指针和0指针 是等价的
    printf("代码执行到这里\n");
    // *q = 100; // 段错误,  空指针(0指针)不能解引用
    // printf("%d\n", *q); //  段错误,  空指针(0指针)不能解引用

    // 5.4  const指针，char指针

    // 5.4.1、const指针
    // const和指针变量一起用，可以限制指针变量本身，也可以限制指针变量所指向的数据
    // const指针有两种形式:  1常指针;  2常目标指针

    // (1)常指针: const修饰指针本身， 表示指针变量指向的地址无法修改， 但是地址中的内容允许修改
    int a = 10;
    int *const p = &a; // 常指针： 指针变量指向的地址无法修改， 但是地址中的内容允许修改

    int b = 20;
    // 修改指针变量指向的地址
    p = &b; // 报错, 常指针，指针变量指向的地址 不允许修改

    // 修改指针指向的地址中的值
    *p = 100; // 通过， 通过地址修改a的值是允许的
    printf("%d\n", a);

    // (2)常目标指针: const修饰指针的目标，表示无法通过指针修改其目标（p指向的空间中的内容不可以改）， 但是指向的地址可以修改
    int a1 = 10;
    const int *p1 = &a1; // 常目标指针： 表示无法通过指针修改其目标,  但是指向的地址可以修改
    // int const * p1 = &a1;  //常目标指针： 表示无法通过指针修改其目标,  但是指向的地址可以修改

    int b1 = 20;
    // 修改指针变量指向的地址
    p1 = &b1; // 通过，常目标指针 指向的地址可以修改

    // 修改指针指向的地址中的值
    *p1 = 100; // 报错， 常目标指针， 无法通过指针修改其目标（p指向的空间中的内容不可以改）
    printf("%d\n", a1);

    // 总结：
    // 1. 常指针修饰指针，指向的地址不能改，内容可以改
    // 2. 常目标指针修饰目标，地址指向的目标不能改，指向的地址可以改  (常目标指针比较常用，在函数接收参数的情境中， 配置常目标指针形参可以避免函数内部修改实参)

    // 当你看到 const int * const p 这种写法时，意味着对指针进行了双重限制

    // **********************************************************************************************
    // char型指针
    // （1）C语言里面，表示字符串的两种方式

    // char型数组:
    char str1[] = "hello world";

    // str1 = "123456"; // 报错：字符串保存在数组中不能直接用等号赋值
    str1[0] = "w";
    printf("str1: %s\n", str1); // "wello world"

    strcpy(str1, "123456"); // 编译通过： strcpy() 修改整个字符串str1
    printf("str1: %s\n", str1); // "123456"


    
    // char型指针：
    char * str2 = "hello world";
    str2 = "123456"; // 编译通过： char型指针可以直接修改指向 到 新的字符串地址
    printf("str2: %s\n", str2); // 123456
    printf("str2[0]: %c\n", str2[0]); // 通过： 可以通过下标访问常量区的值


    str2[0] = 'a'; // 报错： 段错误（不能修改常量区的值）,     char * 不能通过下标修改字符，因为 “hello world”整体存储在常量区， 可以通过str2[0]访问它， 不能修改它
    // 常量区的数据一直不变, 只能访问常量区， 不能修改常量区

    strcpy(str2, "aabbcc"); // 报错： 段错误
    printf("str2:  %s\n", str2);


    // 利用指针 + 双引号的方式定义字符串：会把底层的字符数组放在只读常量区(1.内容不可修改；2.里面定义的字符串可以复用）

}
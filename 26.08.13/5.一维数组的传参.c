#include <stdio.h>

void func1(int a, int b)
{
    // 值传递, 把值赋给形参 a, b,  形参属于局部变量
}

void func2(int *a, int *b)
{
    // 地址传递, 把地址 赋给形参 a, b,  形参属于局部变量
}

void func3(int a[], int b[])
{
    // 地址传递, 传递过来的是数组的地址, 也等于数组的首元素地址

    // 这里就是操作数组 arr1 和 arr2

    // 注意:
    // 虽然说数组的地址确实等于数组首元素地址,
    // 但数组的地址传递到函数内部以后是真的会退化成数组首元素地址,
    // 此时使用 sizeof(数组) 就无法像外面那样获取到数组的内存大小了
}

int main(int argc, char const *argv[])
{

    // 参数的值传递 和 地址传递
    int a = 1, b = 2;
    func1(a, b); // 值传递, 在里面对ab的 操作不会影响 实参ab
    func2(&a, &b); // 地址传递, 在里面对ab地址解引用的操作会对ab 造成影响
    

    // 一维数组的传参
    int arr1[5] = {0}; // 0,0,0,0,0
    int arr2[ ] = {10}; // 10
    
    func3(arr1, arr2); // 地址传递, 把数组的地址作为参数传递

}
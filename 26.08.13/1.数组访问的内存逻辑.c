#include <stdio.h>

int main(int argc, char const *argv[])
{

    // 数组访问的内存逻辑
    // 数组名代表数组首元素的地址,  (绝大多数情况都适用)
    // 不适用的:  sizeof(数组名): sizeof(数组名) 就不再指向数组首元素的大小, 而是得到整个数组所占空间的大小;

    int a[10] = {1, 2, 3};

    printf("首元素地址 %p\n", &a[0]); // 1 的地址 0x7ffd....
    // 数组名 == 首元素地址
    printf("首元素地址 %p\n", a); // 1 的地址 0x7ffd....

    // &a[0]： 数组首元素地址
    // 数组名arr： 数组首元素地址
    // 整个数组的地址 &arr ： 数组首元素地址;
    // 给整个数组的地址解引用  *(&arr)：  数组首元素的地址
    // 以上都是一样的， 但是偏移尺寸时不一样, 寻址的范围也是不一样的

    // 给整个数组的地址解引用 会得到首元素地址
    // &a[0]、 a、  &a   *(&a) 都是数组首元素的地址

    int b = 1;
    printf("sizeof(b) = %ld\n", sizeof(b));       // 4
    printf("sizeof(int) = %ld\n", sizeof(int));   // 4
    printf("sizeof(a[0]) = %ld\n", sizeof(a[0])); // 4
    // sizeof(数组名) 就不再指向数组首元素的大小, 而是得到整个数组所占空间的大小
    printf("sizeof(a) = %ld\n", sizeof(a)); // 此时a代表数组地址,  40:   一个int四个字节, 十个int四十字节

    // 数组空间大小 = 数组每一项的大小 * 数组元素的个数
    // 数组长度 = 数组空间的大小 / 数组项的大小

    // 注意:    arr[n]  等价于  *(arr + n)




    // 注意： 两个 相同大小 相同类型 的数组，其地址是相邻的
    int a[] = {1, 2, 3};
    int b[] = {10, 30, 40};
    

    printf("a = %p\n", a);
    printf("b = %p\n", b); // 两个地址相差 3元素*4字节 = 12字节的大小

    int *p = a;    // 指向数组a的首元素地址
    *(p + 3) = 10; // 按道理会数组越界的，地址指向未知的地方，赋值会段错误， 但是数组b和数组a的地址是相邻的， 所以地址偏移到b数组去了
    printf("%d\n", *(p + 3)); // 成功赋值并输出
    printf("p+3的地址：%p\n", p + 3); // p+3的地址 等于 b的首元素地址
}
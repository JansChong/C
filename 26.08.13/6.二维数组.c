#include <stdio.h>

int main(int argc, char const *argv[])
{

    // 二位数组的概念: 数组元素由多个相同类型的一维数组组成

    // 若数组的类型也是数组, 这种数组称为多维数组

    // 多为数组: 每一个元素都是数组类型 的数组

    int a[5] = {1, 2, 3, 4, 5};

    // 二维数组的定义:

    // arr[2] 表示该数组有两个元素
    // [3] 表示一个有 三个元素 的一维数组  (arr[2]数组的每一项是一个长度为3的数组)
    int arr1[2][3] = {{1, 2, 3}, {4, 5, 6}};

    int arr2[2][3] = {1, 2, 3, 4, 5, 6}; // 编译通过, 里面的花括号可以省略,  里面的元素3个一组

    // 一维数组的长度可以省略, 其余维度的数组(子数组)的长度必须指定界限
    int arr3[][3] = {{1, 2, 3}, {4, 5, 6}}; // 正确
    // int arr3[2][] = {{1, 2, 3}, {4, 5, 6}};  //  错误
    // 将“arr”声明为多维数组, 必须对除第一个维度之外的所有维度设定边界

    // 多维数组的元素访问
    int arr4[][4] = {{1, 2, 3, 4}, {5, 6, 7, 8}};
    // arr4[0] 表示第一个子数组 {1,2,3,4}
    // arr4[1] 表示第二个子数组 {5,6,7,8}
    // arr[1][3] 表示第二个子数组的第四个元素 8

    printf("表示第二个子数组的第四个元素: %d\n", arr4[1][3]);         // 8   通过下标访问
    printf("表示第二个子数组的第四个元素: %d\n", *(arr4[1] + 3));     // 8
    printf("表示第二个子数组的第四个元素: %d\n", *(*(arr4 + 1) + 3)); // 8   通过地址访问
    printf("表示第二个子数组的第四个元素: %d\n", (*(arr4 + 1))[3]);   // 8
    printf("表示第二个子数组的第四个元素: %d\n", *(arr4 + 1)[3]);     //  指针优先级陷阱。  注意:    arr[n]  等价于  *(arr + n),  而[]比*优先级高

    int arr5[2][3] = {1, 2, 3, 4, 5};                                 // 编译通过, 里面的花括号可以省略
    printf("表示第二个子数组的第三个元素: %d\n", arr5[1][2]);         // 0   通过下标访问
    printf("表示第二个子数组的第三个元素: %d\n", *(arr5[1] + 2));     // 0
    printf("表示第二个子数组的第三个元素: %d\n", *(*(arr5 + 1) + 2)); // 0   通过地址访问
    printf("表示第二个子数组的第三个元素: %d\n", (*(arr5 + 1))[2]);   // 0
    printf("表示第二个子数组的第三个元素: %d\n", *(arr5 + 1)[2]);     //   指针优先级陷阱。  注意:    arr[n]  等价于  *(arr + n),  而[]比*优先级高

    // 访问不到
    char arr6[2][3] = {'a', 'b', 'c', 'd', 'e'};                      // 编译通过, 里面的花括号可以省略
    printf("表示第二个子数组的第三个元素: %c\n", arr5[1][2]);         // 0   通过下标访问
    printf("表示第二个子数组的第三个元素: %c\n", *(arr5[1] + 2));     // 0
    printf("表示第二个子数组的第三个元素: %c\n", *(*(arr5 + 1) + 2)); // 0   通过地址访问
    printf("表示第二个子数组的第三个元素: %c\n", (*(arr5 + 1))[2]);   // 0
    printf("表示第二个子数组的第三个元素: %c\n", *(arr5 + 1)[2]);     //   指针优先级陷阱。  注意:    arr[n]  等价于  *(arr + n),  而[]比*优先级高
}
#include <stdio.h> // 头文件调用

// 宏定义的\必须写， 其他\可省略
// \后不能有多余字符


int main() // 主函数main，有且仅有一个，每次程序开始执行，都是从main函数开始执行
{

    // 标点符号可以直接换行
    printf("%d, %f\n", 
        1000,
        1.23456);

    // \ 后面不能有多余字符
    int a = 1 + \
            2;
            
    // 无标点符号且需要换行， \ 不可以省略
    printf("%d      \
        \n", a);

    // 字符串可以直接换行
    char * str = "Line breaks within a string"
     "will not affect compilation";
    

    // 输出语句
    printf("hello world\n");

}



// 预处理:
  // 把头文件内容放进来
  // 进行宏替换  宏定义：文本替换
  // 去掉了注释


// 源文件：C代码，不能直接运行的，放在外部存储器里面 
// 可执行文件：CPU能看懂的文件
// 由指令组成的文件，可以运行的，放在外部存储器里面
// 程序:（可执行文件）运行之后
// 进程：正在执行的程序，动态的，在内存中


// 编译器作用：将编程语言实现的代码编译成某种特定平台计算机系统内的可执行程序
// Ubuntu内部的C语言的编译器
// gcc -v    :查看编译器版本
// gcc version 5.4.0 20160609 (Ubuntu 5.4.0-6ubuntu1~16.04.4)


/* ********************************************************************** */
// 编译过程

// 1.预处理(cpp): 将头文件、宏条件编译等预处理命令进行解析，删掉注释，这个过程是不会检查语法的, 
// 命令：gcc hello.c -o hello.i -E

// 2.编译(ccl)
// 将C语言格式的源码文本编译成适应某个平台的汇编代码，这个过程会检查语法
// gcc hello.i -o hello.s -S

// 3.汇编(as)
// 将汇编文件编译成可重定向文件
// gcc hello.s -o hello.o -c

// 4.链接(ld)
// 链接一些函数库，找到函数的地址
// gcc hello.o -o hello


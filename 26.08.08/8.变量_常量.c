#include <stdio.h>
#include <unistd.h>

int main(int argc, char const *argv[])
{

    // 变量
    // 在使用过程中会发生改变的量，叫做变量
    // 变量分为局部变量，全局变量，静态变量，只读变量

    // 常量
    // 在使用过程中不会发生改变的量，叫做常量
    // 整型常量：
    // 十进制：平常普通的数字：100，200
    // 八进制：通常由0~7的数字组成，以0开头：0123，0256
    // 二进制：由0和1组成：10011，111001
    // 十六进制：由0~9，a~f组成，以0x开头：0xf3，0x4d
    // 浮点型常量：  3.14        2.56        6.1e+10 <==> 6.1*10^10     6.1e-10 <==> 6.1*10^-10
    // 字符型常量：用单引号引起来的单个字符  'a'    'c'    ' '    '2'
    // 字符串常量：用双引号引起来的多个字符，末尾默认以'\0'作为结束符   “hello”    "world"    "a"    " "

    // 注意：有一些字符是不能显示表达的，一般用转义字符（比如：回车\n，制表符\t）
    // 如果要在字符串常量里面使用这些字符，就需要通过转义字符的方式来进行表达/

    // while (1)
    // {
    //     printf("\a\n"); // 响铃  “咚咚咚咚..”
    //     sleep(1);       // 休眠函数，单位秒， 引入头文件 <unistd.h>
    //     // usleep(50000);  // 单位：微秒,  休眠 50 毫秒
    // }

    printf("hello\b\b\bworld\n"); //  \b（退格）： 使光标往前挪，但是并不会删除字符

    printf("hello\b\b\b\vworld\n"); // \v垂直制表符， 使光标挪到下一行的相同位置，  这里能看到上面的退格并不会删除原来的字符

    printf("hello\rworld\n"); // \r 把光标挪到本行的最开始， 会覆盖原来的字符串

    printf("hello\b\b\b\vworld\n");
    printf("hello\b\b\b\fworld\n"); // \f 换页符, 现代控制台只会 增加新行

    printf("hello\tworld\n"); // \t 类似按下tab

    printf("\"\n"); //
    printf("\\\n"); //
    printf("\?\n"); //
    printf("\0\n"); // NULL字符, 在字符串的末尾, \0表示字符串结束
    printf("\'\n"); //

    // \ddd  任意字符 ddd是三位八进制
    // \xhh  任意字符 hh是二位十六进制
    printf("\150\n"); // 0150八进制, 'h'的ascii值
    printf("\100\n"); // 0100八进制, '@'的ascii值
    printf("\x41\n"); // 0x41, 'A'的ascii值

    // 常量
    int a = 10;
    a = 30;
    printf("a = %d\n", a); // 30

    const int b = 20;
    // b = 40;//不能赋值，因为b是只读变量
    printf("b = %d\n", b); // 20

    a = b;
    printf("a = %d\n", a); // 20


    int *c = &b;
    *c = 200;
    printf("b = %d\n", b); // 200
    
    return 0;
}
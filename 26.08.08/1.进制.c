#include <stdio.h> // 头文件调用
// 一、进制
int main()
{

    // 十进制，八进制，二进制，十六进制
    // 十进制：由0~9的数字组成，平常普通的数字：100，200，666 程序中无前缀
    // 十进制科学计数法：格式：尾数 e/E 指数
    int a = -50;
    double b = 9.13E2;       // 9.12 * 10^2
    double c = 1.0086e4;     // 1.0086 * 10^4
    printf("%f %f\n", b, c); // 912 10086

    // 八进制：通常由0~7的数字组成，以0开头：0123，0256，程序中前缀为0
    int d = 067;
    printf("%d\n", d); // %d 按十进制整数输出， 55

    // 二进制：由0和1组成：10011，111001，程序中前缀为0b
    int e = 0b110;
    printf("%d\n", e);

    // 十六进制：由0~9，a~f组成，以0x开头：0xf3，0x4d, 程序中前缀为0x
    int f = 0xf10e;
    printf("%d\n", f);


    // 进制的小数：
    // float a1 = 0b110.11;  // 二进制不支持小数
    float a2 = 017.52; // 八进制增加小数变为十进制表示
    float a3 = 3.14; // 十进制
    float a4 = 0xA.8p1; // 十六进制:  A.8：整数部分是 A（即 10），小数部分是 8，等于 8/16, 前部分的值为10.5;;  p1：表示指数是 2 的1次幂，这里是 2^1 = 2, 整体的值为 10.5 * 2 = 21


    printf("a2 => %f\n", a2); // 17.52
    printf("a3 => %f\n", a3); // 3.14
    printf("a4 => %f\n", a4); // 21
    return 0;
}
#include <stdio.h>

int main()
{

    char a = 129; // %d输出a, a等于-127
    // char a = 128; // %d输出a, a等于-128
    // char a = 256; // %d输出a, a等于0

    printf("%c\n", a);  // 以char类型输出, 129超出char的8位 [-128, 127], 乱码
    printf("%d\n", a); // 以int类型输出 char类型截取到的 129的8位补码, 转成原码就是 -127
    /* code */
    return 0;
  
    ///  int a: 0000 0000 0000 0000 0000 0000 1000 0001 (补码)

    /// char a: 1000 0001 (补码)
             // 1111 1110 (反码)
             // 1111 1111 (原码) 
             // a的值变成了 -127

    // 补码转原码: 可以用补码 再做一次 原码取补码的操作


}

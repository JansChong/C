#include <stdio.h>


int main(int argc, char const *argv[])
{


    int a = 10;
    float b = 3.14;

    printf("%d\n", a); // 输出 整型
    printf("%f\n", b); // 输出 单精度浮点型
    printf("%d %f\n", a, b);

    printf("============================================\n");

    // %d =>  %[正负][宽度][补0]d
    // 正负： 负号左对齐， 正号右对齐
    // 宽度： 输出的数字的长度， 长度不够时用空格补齐
    // 补0:  长度不够时 前置补0 
    printf("%-5d\n"); // 左对齐， 长度为5， 空格补齐    10    
    printf("%5d\n"); // 右对齐， 长度为5， 空格补齐        10
    printf("%05d\n"); // 右对齐， 长度为5， 前置补0     00010

    
    // %f => %[0补齐][总宽度].[小数宽度]f
    printf("%013.10f\n"); // 小数宽度不够后置补0， 总长度13， 总长度不够前置补0，    003.1400001049
    


    // ld  长整型
    long c = 100;
    printf("%ld\n", c);

    // lf双精度浮点型
    long double d = 1.39;
    printf("%Lf\n", d); 




















// 整型			%d 或（%[正负标识][宽度][0补零]d）
// 长整型			%ld
// 无符号整型			%u
// 长无符号整型(unsigned long)		%lu
// 单精度浮点型		%f 或（%[0补齐][总宽度].[小数宽度]f）
// 双精度浮点型		%lf
// 十六进制(小写)		%x
// 十六进制(大写)		%X
// 八进制			%o
// 字符型			%c
// 以十六进制表示地址		%p
// 科学计数法			%e   （变量类型必须是double）
// 字符串			%s   printf访问到\0停止输出
// 短整型			%hd
// 短短整型（单字节整型）	%hhd
// 显示不同进制的前缀: %#o、 %#x
// 补充：
// scanf专用：
//     %d 规则：
//             跳过开头空白（空格、回车、tab）
//             读取连续数字字符，转换成整数；
//             一旦遇到非数字字符，立刻停止解析，该非数字字符放回输入缓冲区，留在 stdin 缓冲里；
//     %s  规则：
//             跳过开头空白（空格、回车、tab）
//             读到空格、换行、制表符就停止
// scanf 格式串里的空白字符（空格、\n、\t）有特殊规则：
//        普通字符（非 %开头）：
//        如果是空白字符(' ' \n \t \r)：匹配并吃掉输入流中任意数量（0 个或多个）连续的空白字符，
//     直到遇到第一个非空白字符才停止。
//        如果是非空白普通字符：要求输入流严格一模一样匹配这个字符，匹配失败 scanf 直接终止。
      
//     %[ ] 是字符集匹配语法
//     规则：
//     %[字符]：只读取括号里包含的字符，遇到不在集合里的字符立刻停止；
//     %[^字符]：取反匹配，读到括号里的字符就停止，只把前面内容读出来。
    


}
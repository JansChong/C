#include <stdio.h>

int main()
{
    // 变量名前有数据类型 表示 "定义变量"
    // 定义变量： 申请一片空间用来保存某个值
    // 空间的大小： 由数据类型决定， 如 float变量 占用 32Bit、4Byte

    /* ######################################################################## */

    // 一、基本类型： （一）数值类型，  （二）字符类型;

    // （一）数值类型： 
    // ** 1. 整型：**

    // 16位短整型， 即占用 16Bit、2Byte
    short a = 53;

    // 32位整型  即占用 32Bit、4Byte
    int b = 100;

    // 长整型
    long c = 256;
    
    // 变量名前没有数据类型， 表示 "访问该变量" 
    a = 10; 


    // ** 2. 浮点型：**

    // 单精度浮点型
    float d = 3.14; 

    // 双精度浮点型
    double g=3.1415;
    // 科学计数法的数据类型： double,
    double g = 1.23e2; // 123

    /* ****************************** */

    // （二）字符类型

    // 8位整型(字符类型)：char本身是8位整型，用来装字符,  8bit即1Byte, 8位等于1字节
    char f1 = 'z'; // ascii码 122
    char f2 = 20;



    /* ######################################################################## */

    // 二、构造类型: 数组、结构体、共用体、枚举

    // 数组
    int arr1[100];

    
    float arr2[100];
    char arr3[100];

    // 结构体： 一般定义在main外面， 类似于 interface 定义, 后面讲


    // unsigned 表示无符号数据类型
    int h1 = 10; // 有符号数据‌（signed） 可正可负可零
    unsigned int h2 = 10; // 无符号数据（unsigned） 只能是正数和零
    unsigned short a = 53; 


    // 浮点型在内存中的存储的第一位就是符号位， 所以不可以用 unsigned 无符号修饰符 

}


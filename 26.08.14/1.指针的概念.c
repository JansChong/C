#include <stdio.h>


int main(int argc, char const *argv[])
{


    // 指针就是指向变量的地址空间，指针是C语言的灵魂

    // 地址的单位是字节， 每一个字节都有地址对应



    // 基地址: 
    // 单字节(比如char)：基地址就是其所在的字节编号
    // 多字节: 多字节的基地址是 其所在字节列表中 最小的那个地址


    // 取址符：
    // 每个变量都是一块内存， 可以通过取址符& 获取其地址（基地址）


    // 虽然不同的变量的尺寸是不同的， 但是他们的地址表示却是一样的； （长度一样）
    // 虽然形式上看起来是一样的， 但是他们所代表的 内存尺寸和类型不同， 因此在逻辑上是严格区分的



    // 概念
    // 指针的概念：专门用来存放地址的变量 （指针、指针变量、地址）

    // 为什么用指针？
    // 指针能够指向某块内存的地址，在使用过程中，它是可以实际反映数据的，特别是在函数调用过程中(例如:两个数进行交换)

    // 什么时候用？
    // 函数传参、匿名空间等

    // 指针的尺寸?
    // (1)指针的尺寸指的是指针本身所占内存的字节数(取决于电脑的位数)
    // 32位机系统指针变量的大小占4Byte(32bit)，64位机系统指针变量的大小占8Byte(64bit)
    // (2)指针所占内存，取决于地址的长度，而地址的长度则取决于系统寻址范围，即字长
    // 结论:指针尺寸只跟系统的字长有关，跟具体的指针的类型无关


    int m = 8;
    
    int *p = &m;
    
    // 二级指针
    int **p1 = &p;



    // 数组不能用二级指针来存

    int arr7[3] = {1,2,3};
    int (*p7)[3] = &arr7;  // p7是数组指针, 

//   int  arr7  [3] = {1,2,3};
//   int  (*p7) [3] = &arr7;  // p7是数组指针, 
//   反正 （*p7）和 arr7 的位置是一样的， 你就当它一样吧[doge]
    
    // int (**p7)[3] = &&arr7; // 错误
    int *p = arr7;


}
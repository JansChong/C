#include <stdio.h>

int main(int argc, char const *argv[])
{

    char str[] = "hello world"; // 可以 用下标修改, 用strcpy替换, 不可以直接替换

    printf("str数组的大小 %ld\n", sizeof(str));

    str[0] = 'a';              // 允许修改
    str[1] = 'b';              // 允许修改
    *(str + 3) = 'c';          // 允许修改
    *(str + 4) = 'd';          // 允许修改
    printf("str = %s\n", str); // ablcd world;

    //===============================================================================================================
    char *str2 = "hello world"; // 可以直接替换整个字符串, 可以用下标读取, 可以解引用指针读取, 不可以用strcpy替换, 不可以用下标赋值, 不可以解引用赋值(因为存在常量区)

    printf("str2[0]: %s\n", str2[0]);       // 可以读取
    printf("str2[1]: %s\n", str2[1]);       // 可以读取
    printf("*str2: %s\n", *str2);           // 可以读取
    printf("*(str2+1): %s\n", *(str2 + 1)); // 可以读取

    // 利用指针 + 双引号的方式定义字符串：会把底层的字符数组放在只读常量区(1.内容不可修改；2.里面定义的字符串可以复用）
    str2[0] = 'a';     // 段错误
    str2[1] = 'b';     // 段错误
    *str2 = 'c';       // 段错误
    *(str2 + 1) = 'd'; // 段错误

    
    // ==========================================================================================================================
    char *str3 = malloc(12);
    if (str3 == NULL)
        printf("空间申请失败\n");
    else
        printf("空间申请成功\n");

    // str3 = "hello world"; // 这样的话 跟 第二种没什么区别, 字符串还是在常量区, 不可以用下标修改

    // 给字符串拷贝到指定的空间str3中
    strcpy(str3, "hello world"); // 此时的字符串存在 malloc申请的堆空间中
    printf("str3 = %s\n", str3);  // 可以访问
    // 这里的字符串存在 malloc申请的堆空间中
    str3[0] = 'a';     // 可以修改堆空间中的字符串
    str3[1] = 'b';     // 可以修改堆空间中的字符串
    *str3 = 'c';       // 可以修改堆空间中的字符串
    *(str3 + 1) = 'd'; // 可以修改堆空间中的字符串

    
}